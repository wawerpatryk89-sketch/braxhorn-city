#!/usr/bin/env python3
"""Measure the outer silhouette of the owner's four CHAMPION ARENA sign PNGs.

Owner 9.11: "Szyld ma być naklejony na bryle żeby wyglądał jak 3d".
The sign body in Unity is the artwork's own outline extruded in depth, so the
silhouette must come from the artwork alpha (same .12 cutoff as the material),
not from a hand-drawn guess. Output: BraxChampionsArenaSignSilhouettes.cs with
(u,v) points, u=x/width, v=1-y/height (v up), counter-clockwise in UV space.

Usage: make_arena_sign_silhouettes.py <dir with the four owner PNGs>
The PNGs come from the owner asset zip (verify_champion_assets.py pins them);
the hashes are written into the C# so a changed artwork cannot reuse old data.
"""
from pathlib import Path
import hashlib
import sys

import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "unity-city/Assets/Editor/Mistrzowie/BraxChampionsArenaSignSilhouettes.cs"
NAMES = [
    "champion_arena_red_front.png",
    "champion_arena_gold_front.png",
    "champion_arena_red_fight_night.png",
    "champion_arena_gold_arena_walk.png",
]
CUTOFF = .12        # material _Cutoff
EPSILON_PX = 1.2    # polygon tolerance in source pixels


def silhouette(blob):
    image = cv2.imdecode(np.frombuffer(blob, np.uint8), cv2.IMREAD_UNCHANGED)
    if image is None or image.ndim != 3 or image.shape[2] != 4:
        raise ValueError("sign PNG must be RGBA")
    h, w = image.shape[:2]
    mask = (image[:, :, 3] > int(CUTOFF * 255)).astype(np.uint8)
    mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8))
    contours, _ = cv2.findContours(mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_NONE)
    main = max(contours, key=cv2.contourArea)
    poly = cv2.approxPolyDP(main, EPSILON_PX, True).reshape(-1, 2).astype(float)
    uv = [((x + .5) / w, 1. - (y + .5) / h) for x, y in poly]
    area = sum(uv[i][0] * uv[(i + 1) % len(uv)][1] - uv[(i + 1) % len(uv)][0] * uv[i][1]
               for i in range(len(uv))) * .5
    if area < 0:
        uv.reverse()
    return w, h, uv


def main():
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    src = Path(sys.argv[1])
    lines = [
        "// GENERATED by unity-tools/mistrzowie/make_arena_sign_silhouettes.py - do not edit.",
        "// Outer silhouette of the owner's sign artwork (alpha > .12), u right, v up, CCW.",
        "public static class BraxChampionsArenaSignSilhouettes",
        "{",
    ]
    arrays = []
    for name in NAMES:
        blob = (src / name).read_bytes()
        w, h, uv = silhouette(blob)
        digest = hashlib.sha256(blob).hexdigest()
        lines.append(f"    // {name} {w}x{h} sha256={digest} points={len(uv)}")
        flat = ",".join(f"{u:.5f}f,{v:.5f}f" for u, v in uv)
        arrays.append(f"S{len(arrays)}")
        lines.append(f"    static readonly float[] S{len(arrays) - 1}={{{flat}}};")
    lines.append("    public static readonly float[][] UV={" + ",".join(arrays) + "};")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("BRAX_A1_SIGN_SILHOUETTES", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
