import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
import fs from 'fs';
const [url, prefix, viewsJson] = process.argv.slice(2);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--js-flags=--max-old-space-size=7000'] });
const page = await browser.newPage();
await page.goto('http://127.0.0.1:8765/tools/shot.html'); await page.waitForFunction(() => window.ready);
const r = await page.evaluate(([u, v]) => window.shots(u, v), [url, JSON.parse(viewsJson || '[[0.7,0.5],[3.8,0.3],[0,1.4]]')]);
console.log(JSON.stringify(r.box));
r.out.forEach((d, i) => fs.writeFileSync(`${prefix}_${i}.jpg`, Buffer.from(d.split(',')[1], 'base64')));
await browser.close();
